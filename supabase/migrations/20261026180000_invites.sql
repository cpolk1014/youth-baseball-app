-- Invite links: a coach shares a link (GroupMe, text, email); whoever opens it signs in,
-- enters their name, and joins the team with the link's role. No emails are stored.

-- Members are shown by the name they give when joining (e.g. "Sam's mom").
alter table public.member
  add column display_name text check (display_name is null or length(trim(display_name)) between 1 and 60);

create table public.invite (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.team (id) on delete cascade,
  role public.member_role not null,
  -- Unguessable token from the link (generated by the app).
  token text not null unique check (length(token) >= 32),
  created_by uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '14 days',
  -- null = any number of people (e.g. one parent link for the whole team).
  max_uses integer check (max_uses is null or max_uses >= 1),
  uses integer not null default 0,
  revoked_at timestamptz
);

create index on public.invite (team_id);

alter table public.invite enable row level security;

create policy "coaches can see their team's invites" on public.invite
  for select to authenticated using (public.has_team_role(team_id, '{coach}'));
create policy "coaches can create invites" on public.invite
  for insert to authenticated
  with check (public.has_team_role(team_id, '{coach}') and created_by = (select auth.uid()));
create policy "coaches can revoke invites" on public.invite
  for update to authenticated
  using (public.has_team_role(team_id, '{coach}'))
  with check (public.has_team_role(team_id, '{coach}'));
create policy "coaches can delete invites" on public.invite
  for delete to authenticated using (public.has_team_role(team_id, '{coach}'));

-- What an invite link is for, before accepting. Callable by any signed-in user who has
-- the token; reveals only the team name and role.
create function public.invite_preview(p_token text)
returns table (team_id uuid, team_name text, role public.member_role, valid boolean, already_member boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select
    i.team_id,
    t.name,
    i.role,
    i.revoked_at is null
      and i.expires_at > now()
      and (i.max_uses is null or i.uses < i.max_uses),
    exists (
      select 1 from public.member m where m.team_id = i.team_id and m.user_id = (select auth.uid())
    )
  from public.invite i
  join public.team t on t.id = i.team_id
  where i.token = p_token;
$$;

-- Join the team an invite is for. Returns the team id.
create function public.accept_invite(p_token text, p_display_name text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invite public.invite;
  v_user uuid := (select auth.uid());
begin
  if v_user is null then
    raise exception 'sign in to accept an invite' using errcode = '42501';
  end if;

  select * into v_invite from public.invite where token = p_token for update;
  if v_invite.id is null
    or v_invite.revoked_at is not null
    or v_invite.expires_at <= now()
    or (v_invite.max_uses is not null and v_invite.uses >= v_invite.max_uses) then
    raise exception 'this invite link is no longer valid' using errcode = 'P0002';
  end if;

  if exists (select 1 from public.member where team_id = v_invite.team_id and user_id = v_user) then
    return v_invite.team_id;
  end if;

  insert into public.member (team_id, user_id, role, display_name)
  values (v_invite.team_id, v_user, v_invite.role, nullif(trim(p_display_name), ''));
  update public.invite set uses = uses + 1 where id = v_invite.id;
  return v_invite.team_id;
end;
$$;

revoke execute on function public.invite_preview(text) from public, anon;
revoke execute on function public.accept_invite(text, text) from public, anon;
grant execute on function public.invite_preview(text) to authenticated;
grant execute on function public.accept_invite(text, text) to authenticated;

-- A team always keeps at least one coach (removing or demoting the last one fails).
-- Skipped when the whole team is being deleted.
create function public.keep_a_coach()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.role = 'coach'
    and (tg_op = 'DELETE' or new.role <> 'coach' or new.team_id <> old.team_id)
    and exists (select 1 from public.team where id = old.team_id)
    and not exists (
      select 1 from public.member
      where team_id = old.team_id and role = 'coach' and id <> old.id
    ) then
    raise exception 'a team needs at least one coach';
  end if;
  return coalesce(new, old);
end;
$$;

create trigger member_keep_a_coach
before update or delete on public.member
for each row execute function public.keep_a_coach();
